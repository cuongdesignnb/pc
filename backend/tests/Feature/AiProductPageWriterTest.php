<?php

namespace Tests\Feature;

use App\Models\Product;
use App\Models\User;
use App\Support\HtmlToText;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Facades\Http;
use Spatie\Permission\Models\Permission;
use Tests\TestCase;

class AiProductPageWriterTest extends TestCase
{
    use RefreshDatabase;

    protected function setUp(): void
    {
        parent::setUp();
        config()->set('ai.content.api_key', 'content-key');
        config()->set('ai.content.base_url', 'https://modelapi.vn/v1');
        config()->set('ai.content.wire_api', 'chat_completions');
        config()->set('ai.content.max_tokens', 4096);
        config()->set('integrations.kiot.enabled', false);
    }

    public function test_product_writer_returns_description_specs_highlights_and_blocks(): void
    {
        $this->fakeProvider([
            'short_description' => 'Laptop doanh nhân bền bỉ.',
            'content' => '<h2>Tổng quan</h2><p>Dell Latitude 5480 <script>alert(1)</script>bền bỉ.</p><ul><li>Bàn phím tốt</li></ul>',
            'meta_title' => 'Dell Latitude 5480 i5-6440HQ 8GB 256GB',
            'meta_desc' => 'Laptop Dell Latitude 5480 cấu hình i5-6440HQ.',
            'specifications' => [
                ['label' => 'CPU', 'value' => 'Intel Core i5-6440HQ'],
                ['label' => 'RAM', 'value' => '8GB DDR4'],
                ['label' => 'Ổ cứng: SSD', 'value' => 'dropped because label has a colon'],
                ['label' => 'RAM', 'value' => 'duplicate label dropped'],
                ['label' => 'Màn hình', 'value' => '<b>14 inch FHD</b>'],
            ],
            'highlights' => ['Core i5 4 nhân', 'SSD 256GB', ['title' => 'Màn hình FHD']],
            'detail_blocks' => [
                ['type' => 'benchmark_cards', 'title' => 'Cấu hình nổi bật', 'cards' => [['title' => 'CPU', 'value' => 'i5-6440HQ', 'description' => '4 nhân']]],
                ['type' => 'use_case_cards', 'title' => 'Phù hợp cho', 'cards' => [['icon' => '💼', 'title' => 'Văn phòng']]],
                ['type' => 'hero_banner', 'title' => 'not generated by AI', 'cards' => [['title' => 'x']]],
                ['type' => 'feature_cards', 'title' => 'Empty block dropped', 'cards' => []],
            ],
        ]);

        $response = $this->actingAs($this->editor())->postJson('/api/ai/content', $this->payload())
            ->assertOk()
            ->assertJsonPath('success', true)
            ->assertJsonPath('specifications_text', "CPU: Intel Core i5-6440HQ\nRAM: 8GB DDR4\nMàn hình: 14 inch FHD")
            ->assertJsonPath('highlights', ['Core i5 4 nhân', 'SSD 256GB', 'Màn hình FHD'])
            ->assertJsonPath('detail_blocks.0.type', 'benchmark_cards')
            ->assertJsonPath('detail_blocks.0.payload.cards.0.value', 'i5-6440HQ')
            ->assertJsonPath('detail_blocks.1.payload.cards.0.icon', '💼')
            ->assertJsonCount(2, 'detail_blocks')
            ->assertJsonPath('sections', ['description', 'specifications', 'highlights', 'blocks']);

        $this->assertStringNotContainsString('<script', $response->json('content'));
        $this->assertStringContainsString('<h2>Tổng quan</h2>', $response->json('content'));

        Http::assertSent(fn ($request) => $request['max_tokens'] >= 8000
            && str_contains($request['messages'][1]['content'], 'Dell Latitude 5480 i5-6440HQ/Ram 8GB/SSD 256GB/14" FHD'));
    }

    public function test_only_requested_sections_are_filled(): void
    {
        $this->fakeProvider([
            'specifications' => [['label' => 'CPU', 'value' => 'Intel Core i5-6440HQ']],
            'highlights' => ['should be ignored'],
        ]);

        $this->actingAs($this->editor())->postJson('/api/ai/content', $this->payload(['sections' => ['specifications']]))
            ->assertOk()
            ->assertJsonPath('specifications_text', 'CPU: Intel Core i5-6440HQ')
            ->assertJsonPath('highlights', [])
            ->assertJsonPath('detail_blocks', [])
            ->assertJsonPath('content', '');

        Http::assertSent(fn ($request) => ! str_contains($request['messages'][1]['content'], '"highlights"'));
    }

    public function test_invalid_json_from_provider_is_reported(): void
    {
        Http::fake(['https://modelapi.vn/v1/chat/completions' => Http::response([
            'choices' => [['message' => ['content' => '{"content": "<p>cut off']]],
        ])]);

        $this->actingAs($this->editor())->postJson('/api/ai/content', $this->payload())
            ->assertStatus(502)
            ->assertJsonPath('success', false);
    }

    public function test_unknown_section_is_rejected(): void
    {
        Http::fake();

        $this->actingAs($this->editor())->postJson('/api/ai/content', $this->payload(['sections' => ['prices']]))
            ->assertStatus(422);
        Http::assertNothingSent();
    }

    public function test_storefront_description_keeps_paragraphs_and_bullets(): void
    {
        $this->assertSame(
            "Tổng quan\n\nMáy bền bỉ & nhẹ.\n\n• Bàn phím tốt\n• Pin ổn",
            HtmlToText::convert('<h2>Tổng quan</h2><p>Máy bền bỉ &amp; nhẹ.</p><ul><li>Bàn phím tốt</li><li>Pin ổn</li></ul><script>x()</script>'),
        );
        $this->assertNull(HtmlToText::convert('<p> </p>'));

        $product = Product::create([
            'name' => 'Dell Latitude 5480', 'slug' => 'dell-latitude-5480', 'sku' => 'DL5480',
            'price' => 1000, 'stock_quantity' => 1, 'is_active' => true, 'show_on_pc_website' => true,
            'inventory_source' => 'local', 'description' => '<h2>Tổng quan</h2><p>Máy bền.</p>',
        ]);
        $this->getJson('/api/v1/products/'.$product->slug)
            ->assertOk()
            ->assertJsonPath('product.description', "Tổng quan\n\nMáy bền.");
    }

    private function fakeProvider(array $json): void
    {
        Http::fake(['https://modelapi.vn/v1/chat/completions' => Http::response([
            'choices' => [['message' => ['content' => json_encode($json, JSON_UNESCAPED_UNICODE)]]],
        ])]);
    }

    private function payload(array $overrides = []): array
    {
        return array_replace([
            'topic' => 'Dell Latitude 5480 i5-6440HQ/Ram 8GB/SSD 256GB/14" FHD',
            'type' => 'product_description',
            'keywords' => 'Dell Latitude 5480',
            'tone' => 'professional',
            'length' => 'medium',
        ], $overrides);
    }

    private function editor(): User
    {
        $user = User::factory()->create(['role' => 'admin']);
        $user->givePermissionTo(Permission::firstOrCreate(['name' => 'products.edit', 'guard_name' => 'web']));

        return $user;
    }
}
